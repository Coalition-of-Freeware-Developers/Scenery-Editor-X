class GatewayHandler(BaseHTTPRequestHandler):
    server_version = "SceneryGatewayMock/1.0"
    data = None         # GatewayData, set by make_server
    quiet = False

    # --- plumbing ---

    def log_message(self, fmt, *args):
        if not self.quiet:
            sys.stderr.write("[gateway-mock] %s %s\n" % (self.address_string(), fmt % args))

    def send_json(self, status, payload):
        body = json.dumps(payload).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("X-Gateway-Mock", "1")     # Lets a client (or a test) see it isn't the real Gateway
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)

    def send_error_json(self, status, message):
        self.send_json(status, {"message": message})

    def api_path(self):
        path = unquote(urlsplit(self.path).path)
        if path != API_ROOT and not path.startswith(API_ROOT + "/"):
            return None
        return path[len(API_ROOT):].rstrip("/") or "/"

    def read_json_body(self):
        length = int(self.headers.get("Content-Length") or 0)
        if length <= 0:
            raise ValueError("the request has no body")
        if length > MAX_BODY_BYTES:
            raise ValueError(f"the request body is over {MAX_BODY_BYTES // (1024 * 1024)} MB")
        raw = self.rfile.read(length)
        try:
            return json.loads(raw.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError) as e:
            raise ValueError(f"the body isn't JSON: {e}")

    # --- routes ---

    def do_GET(self):
        path = self.api_path()
        if path is None:
            return self.send_error_json(HTTPStatus.NOT_FOUND, "Not an API path (the API lives under /apiv1)")
        data = self.data
        with data.lock:
            if path == "/airports":
                return self.send_json(HTTPStatus.OK, data.airport_list())
            if path == "/stats":
                return self.send_json(HTTPStatus.OK, data.stats())
            if path == "/releases":
                return self.send_json(HTTPStatus.OK, {"releases": [
                    {"Version": "12.1.0", "Date": "2024-05-01T00:00:00.000Z"},
                    {"Version": "12.0.0", "Date": "2022-09-06T00:00:00.000Z"},
                ]})
            match = re.fullmatch(r"/airport/([^/]+)", path)
            if match:
                details = data.airport_details(match.group(1))
                if not details:
                    return self.send_error_json(HTTPStatus.NOT_FOUND, f"No airport {match.group(1)}")
                return self.send_json(HTTPStatus.OK, details)
            match = re.fullmatch(r"/scenery/(\d+)", path)
            if match:
                record = data.scenery.get(int(match.group(1)))
                if not record:
                    return self.send_error_json(HTTPStatus.NOT_FOUND, f"No scenery {match.group(1)}")
                return self.send_json(HTTPStatus.OK, {"scenery": record})
            if path == "/mock/log":
                # Test hook: what the server received (passwords are never logged)
                return self.send_json(HTTPStatus.OK, {"signIns": data.sign_ins, "uploads": data.uploads})
        return self.send_error_json(HTTPStatus.NOT_FOUND, f"Unknown API path {path}")

    do_HEAD = do_GET

    def do_PUT(self):
        path = self.api_path()
        if path != "/scenery":
            return self.send_error_json(HTTPStatus.NOT_FOUND, f"Unknown API path {path}")
        try:
            body = self.read_json_body()
        except ValueError as e:
            return self.send_error_json(HTTPStatus.BAD_REQUEST, str(e))
        return self.handle_upload(body)

    def do_POST(self):
        # The real Gateway takes uploads as PUT (WorldEditor's CURLOPT_UPLOAD); a POST is a client bug worth seeing
        return self.send_error_json(HTTPStatus.METHOD_NOT_ALLOWED, "Uploads are PUT /apiv1/scenery")

    def send_text(self, status, text):
        # The live Gateway answers some refusals with a short text/html line (seen: 401 for an unsupported build)
        body = text.encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("X-Gateway-Mock", "1")
        self.end_headers()
        self.wfile.write(body)

    def handle_upload(self, body):
        data = self.data
        scenery = body.get("scenery") if isinstance(body, dict) else None
        if not isinstance(scenery, dict):
            return self.send_error_json(HTTPStatus.BAD_REQUEST, 'The body must be {"scenery": {...}}')

        user = scenery.get("userId")
        password = scenery.get("password")
        icao = scenery.get("icao")
        record = {
            "time": now_iso(), "userId": user if isinstance(user, str) else None, "icao": icao,
            "parentId": scenery.get("parentId"), "type": scenery.get("type"),
            "validatedAgainst": scenery.get("validatedAgainst"), "clientVersion": scenery.get("clientVersion"),
            "userAgent": self.headers.get("User-Agent"), "result": None,
        }

        credentials_ok = None       # Not checked yet

        def finish(status, reply, text=False):
            record["result"] = int(status)
            with data.lock:
                data.uploads.append(record)
                if credentials_ok is not None:
                    data.sign_ins.append({"time": record["time"], "userId": record["userId"], "accepted": credentials_ok})
            return self.send_text(status, reply) if text else self.send_json(status, reply)

        if data.maintenance:
            return finish(HTTPStatus.SERVICE_UNAVAILABLE, "The Gateway is locked for maintenance (mock --maintenance)", text=True)

        # Credentials: plain fields in the body, checked only here (the API has no sign-in call)
        credentials_ok = isinstance(user, str) and isinstance(password, str) and data.accounts.get(user) == password
        if not credentials_ok:
            return finish(HTTPStatus.UNAUTHORIZED, "Invalid username or password (mock)", text=True)

        if data.supported_versions is not None and scenery.get("validatedAgainst") not in data.supported_versions:
            return finish(HTTPStatus.UNAUTHORIZED,
                          "Invalid X-Plane Version. Please check the NOTAMS Gateway page for supported versions.", text=True)

        if not isinstance(icao, str) or icao.upper() not in data.airports:
            return finish(HTTPStatus.NOT_FOUND, {"message": f"Unknown airport code {icao}"})
        icao = icao.upper()

        if scenery.get("type") not in ("2D", "3D"):
            return finish(HTTPStatus.BAD_REQUEST, {"message": "type must be 2D or 3D"})

        parent = scenery.get("parentId")
        if parent in (None, "", 0):
            parent_id = 0
        else:
            try:
                parent_id = int(parent)         # WED sends it as a string, the docs as a number
            except (TypeError, ValueError):
                return finish(HTTPStatus.BAD_REQUEST, {"message": f"parentId {parent!r} isn't a scenery id"})
            if parent_id not in data.scenery:
                return finish(HTTPStatus.BAD_REQUEST, {"message": f"parentId {parent_id} doesn't exist"})

        try:
            master_zip = base64.b64decode(scenery.get("masterZipBlob") or "", validate=True)
            with zipfile.ZipFile(io.BytesIO(master_zip)) as archive:
                names = archive.namelist()
                archive.testzip()
        except (ValueError, zipfile.BadZipFile) as e:
            return finish(HTTPStatus.BAD_REQUEST, {"message": f"masterZipBlob isn't a base64 zip archive: {e}"})
        if f"{icao}.dat" not in names:
            return finish(HTTPStatus.BAD_REQUEST, {"message": f"masterZipBlob has no {icao}.dat"})
        # What the scenery pack holds, for the log (the real server's checks of it are unknown, so none are made)
        pack_files = None
        if f"{icao}_Scenery_Pack.zip" in names:
            try:
                with zipfile.ZipFile(io.BytesIO(master_zip)) as archive:
                    with zipfile.ZipFile(io.BytesIO(archive.read(f"{icao}_Scenery_Pack.zip"))) as pack:
                        pack_files = pack.namelist()
            except (zipfile.BadZipFile, KeyError, ValueError):
                pack_files = None

        with data.lock:
            stored = data._add_scenery(icao, user, data.user_ids.get(user, 70000), None, scenery["type"],
                                       scenery.get("features") or "", scenery.get("artistComments") or "",
                                       parent_id=parent_id, master_zip=master_zip)
            metadata = scenery.get("additionalMetadata")
            if isinstance(metadata, dict):
                stored["additionalMetadata"] = {str(k): str(v) for k, v in metadata.items()}
        record["sceneryId"] = stored["sceneryId"]
        record["files"] = names
        record["packFiles"] = pack_files
        record["features"] = scenery.get("features")
        self.save_upload(stored["sceneryId"], scenery, master_zip)
        return finish(HTTPStatus.OK, {"sceneryId": stored["sceneryId"]})

    def save_upload(self, scenery_id, scenery, master_zip):
        """What arrived, for inspection: the request without the password or the (decoded separately) blob."""
        folder = os.path.join(self.data.state_dir, str(scenery_id))
        os.makedirs(folder, exist_ok=True)
        shown = {k: v for k, v in scenery.items() if k not in ("password", "masterZipBlob")}
        shown["masterZipBlob"] = f"<{len(master_zip)} bytes: masterZip.zip>"
        with open(os.path.join(folder, "request.json"), "w", encoding="utf-8") as f:
            json.dump({"scenery": shown}, f, indent=2)
        with open(os.path.join(folder, "masterZip.zip"), "wb") as f:
            f.write(master_zip)


def make_server(host, port, data, quiet=False):
    handler = type("BoundGatewayHandler", (GatewayHandler,), {"data": data, "quiet": quiet})
    if ":" in host:
        class IPv6Server(ThreadingHTTPServer):
            address_family = __import__("socket").AF_INET6
        return IPv6Server((host, port), handler)
    return ThreadingHTTPServer((host, port), handler)


# -------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description=__doc__ or "Scenery Gateway test server")
    parser.add_argument("--port", type=int, default=DEFAULT_PORT, help=f"port to listen on (default {DEFAULT_PORT})")
    parser.add_argument("--host", default="127.0.0.1", help="loopback address to listen on (127.0.0.1, ::1 or localhost)")
    parser.add_argument("--account", action="append", default=[], metavar="NAME:PASSWORD",
                        help=f"a test artist account (repeatable); default {DEFAULT_ACCOUNT[0]}:{DEFAULT_ACCOUNT[1]}")
    parser.add_argument("--state", default=None, help="folder for received uploads (default: a new temp folder)")
    parser.add_argument("--supported-version", action="append", default=None, metavar="BUILD",
                        help="only take uploads validated against this X-Plane build, e.g. 12.1.3-r2-2f236 (repeatable); "
                             "others get the live Gateway's 401 'Invalid X-Plane Version'")
    parser.add_argument("--maintenance", action="store_true", help="refuse every upload with 503, like a locked Gateway")
    parser.add_argument("--quiet", action="store_true", help="don't log each request")
    args = parser.parse_args()

    if args.host not in LOOPBACK_HOSTS:
        parser.error("the test server only listens on this computer (127.0.0.1, ::1 or localhost)")

    accounts = {}
    for entry in args.account or [f"{DEFAULT_ACCOUNT[0]}:{DEFAULT_ACCOUNT[1]}"]:
        name, sep, password = entry.partition(":")
        if not sep or not name or not password:
            parser.error(f"--account needs NAME:PASSWORD, got {entry!r}")
        accounts[name] = password

    state_dir = args.state or tempfile.mkdtemp(prefix="sedx-gateway-mock-")
    os.makedirs(state_dir, exist_ok=True)
    data = GatewayData(accounts, state_dir, supported_versions=args.supported_version, maintenance=args.maintenance)

    server = make_server(args.host, args.port, data, quiet=args.quiet)
    host, port = server.server_address[:2]
    shown = f"[{host}]" if ":" in host else host
    print(f"Scenery Gateway test server: http://{shown}:{port}{API_ROOT}", flush=True)
    print(f"  accounts: {', '.join(sorted(accounts))}", flush=True)
    print(f"  uploads go to: {state_dir}", flush=True)
    print("  Ctrl+C stops it", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
