class GatewayData:
    """Everything the mock serves, kept in memory and (uploads) mirrored to the state folder."""

    def __init__(self, accounts, state_dir, supported_versions=None, maintenance=False):
        self.lock = threading.Lock()
        self.accounts = dict(accounts)          # name -> password
        self.supported_versions = supported_versions    # None: any validatedAgainst is taken
        self.maintenance = maintenance          # Refuse every upload with 503
        self.user_ids = {name: 70001 + i for i, name in enumerate(sorted(self.accounts))}
        self.state_dir = state_dir
        self.next_scenery_id = FIRST_SCENERY_ID
        self.airports = {}                      # code -> airport dict (Gateway field names)
        self.scenery = {}                       # id -> scenery dict incl. masterZipBlob
        self.uploads = []                       # log of upload attempts (for tests)
        self.sign_ins = []                      # log of credential checks (for tests)
        self._seed()

    def _seed(self):
        # Codes of the user's usual test airports, with made-up data so a mix-up with real scenery is plain to see
        for code, name, lat, lon, elev in [
            ("KGON", "Groton New London (MOCK)", 41.3302, -72.0451, 10),
            ("KDEN", "Denver Intl (MOCK)", 39.8617, -104.6731, 5434),
            ("KORD", "Chicago O'Hare Intl (MOCK)", 41.9786, -87.9048, 680),
            ("KBOS", "Boston Logan Intl (MOCK)", 42.3656, -71.0096, 20),
            ("KBTV", "Burlington Intl (MOCK)", 44.4719, -73.1533, 335),
            ("XSDX", "Scenery Editor X Test Field (MOCK)", 45.0, -100.0, 1500),
        ]:
            self.airports[code] = {
                "icao": code, "airportName": name, "latitude": lat, "longitude": lon, "elevation": elev,
                "acceptedSceneryCount": 0, "approvedSceneryCount": 0, "recommendedSceneryId": None,
                "checkedOutBy": None, "checkOutEndDate": None, "status": "Awaiting Scenery",
                "sceneryType": 0, "submissionCount": 0, "deprecated": None, "deprecatedInFavorOf": None,
            }
        # One approved 2D submission each for two of them, so downloads work out of the box
        for code in ("KBTV", "XSDX"):
            airport = self.airports[code]
            apt = make_apt_dat(code, airport["airportName"], airport["latitude"], airport["longitude"], airport["elevation"])
            self._add_scenery(code, "Mock Seed", 70000, apt, "2D", "", "Seeded by the test server", status="Approved")

    # ---------------------------------------------------

    def _add_scenery(self, icao, user_name, user_id, apt_dat_text_or_none, scenery_type, features, comments,
                     parent_id=0, status="Uploaded", master_zip=None):
        scenery_id = self.next_scenery_id
        self.next_scenery_id += 1
        if master_zip is None:
            master_zip = make_master_zip(icao, apt_dat_text_or_none or "")
        stamp = now_iso()
        record = {
            "sceneryId": scenery_id, "parentId": parent_id or None, "icao": icao,
            "aptName": self.airports.get(icao, {}).get("airportName", icao),
            "userId": user_id, "userName": user_name,
            "dateUploaded": stamp,
            "dateAccepted": stamp if status in ("Accepted", "Approved") else None,
            "dateApproved": stamp if status == "Approved" else None,
            "dateDeclined": None,
            "type": scenery_type, "features": features or None, "artistComments": comments or None,
            "moderatorComments": "Approved by the mock moderator." if status == "Approved" else None,
            "Status": status,
            "additionalMetadata": dict(SEED_METADATA),
            "masterZipBlob": base64.b64encode(master_zip).decode("ascii"),
        }
        self.scenery[scenery_id] = record
        airport = self.airports.setdefault(icao, {
            "icao": icao, "airportName": icao, "latitude": 0.0, "longitude": 0.0, "elevation": None,
            "acceptedSceneryCount": 0, "approvedSceneryCount": 0, "recommendedSceneryId": None,
            "checkedOutBy": None, "checkOutEndDate": None, "status": "Awaiting Scenery",
            "sceneryType": 0, "submissionCount": 0, "deprecated": None, "deprecatedInFavorOf": None,
        })
        airport["submissionCount"] += 1
        airport["status"] = "Scenery Submitted"
        if status in ("Accepted", "Approved"):
            airport["acceptedSceneryCount"] += 1
        if status == "Approved":
            airport["approvedSceneryCount"] += 1
            airport["recommendedSceneryId"] = scenery_id
        airport["sceneryType"] = max(airport["sceneryType"], 2 if scenery_type == "3D" else 1)
        return record

    # ---------------------------------------------------

    def airport_list(self):
        rows = []
        for a in self.airports.values():
            rows.append({
                "AirportCode": a["icao"], "AirportName": a["airportName"], "Latitude": a["latitude"],
                "Longitude": a["longitude"], "Elevation": a["elevation"],
                "AcceptedSceneryCount": a["acceptedSceneryCount"], "ApprovedSceneryCount": a["approvedSceneryCount"],
                "RecommendedSceneryId": a["recommendedSceneryId"], "Status": a["status"],
                "SceneryType": a["sceneryType"], "SubmissionCount": a["submissionCount"],
                "Deprecated": a["deprecated"], "DeprecatedInFavorOf": a["deprecatedInFavorOf"],
            })
        return {"total": len(rows), "airports": rows}

    def airport_details(self, code):
        airport = self.airports.get(code.upper())
        if not airport:
            return None
        scenery = []
        for record in self.scenery.values():
            if record["icao"] == airport["icao"]:
                scenery.append({k: v for k, v in record.items() if k not in ("masterZipBlob", "additionalMetadata", "icao", "aptName")})
        result = dict(airport)
        result["scenery"] = sorted(scenery, key=lambda s: s["sceneryId"])
        return {"airport": result}

    def stats(self):
        return {"stats": {
            "airports": len(self.airports), "userSceneryPacks": len(self.scenery),
            "sceneryPacks3D": sum(1 for s in self.scenery.values() if s["type"] == "3D"),
            "artists": len(self.accounts),
        }}


