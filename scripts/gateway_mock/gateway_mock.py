# Made-up scenery: a tiny but valid apt.dat 12 airport, packed the way WorldEditor uploads it
# -------------------------------------------------------

SEED_METADATA = {"city": "Mockville", "country": "USA United States"}


def make_apt_dat(icao, name, lat, lon, elevation_ft):
    """A one-runway land airport with the 1302 rows the Gateway expects. It passes WorldEditor's Gateway checks
    (ISO-3166 country prefix, datum next to the airport, runway inside a boundary with 30 m+ sides), so a downloaded
    seed can be uploaded back unchanged."""
    lat2 = lat + 0.009
    return "\n".join([
        "I",
        "1200 Generated by gateway_mock.py (Scenery Editor X test server) - not real data",
        "",
        f"1 {elevation_ft} 0 0 {icao} {name}",
        f"1302 city {SEED_METADATA['city']}",
        f"1302 country {SEED_METADATA['country']}",
        f"1302 datum_lat {lat:.8f}",
        f"1302 datum_lon {lon:.8f}",
        f"1302 gui_label 2D",
        f"1302 icao_code {icao}",
        f"1302 region_code K1",
        f"100 30.00 1 0 0.25 0 2 0 18 {lat:.8f} {lon:.8f} 0 0 2 0 0 0 36 {lat2:.8f} {lon:.8f} 0 0 2 0 0 0",
        "130 Airport Boundary",
        f"111 {lat - 0.002:.8f} {lon - 0.002:.8f}",
        f"111 {lat - 0.002:.8f} {lon + 0.002:.8f}",
        f"111 {lat2 + 0.002:.8f} {lon + 0.002:.8f}",
        f"113 {lat2 + 0.002:.8f} {lon - 0.002:.8f}",
        "",
        "99",
        "",
    ])


def zip_bytes(files):
    """files: list of (name, bytes) -> deflated zip archive bytes."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, data in files:
            archive.writestr(name, data)
    return buffer.getvalue()


def make_master_zip(icao, apt_dat_text):
    """masterZipBlob layout WorldEditor uses: <ICAO>.dat, <ICAO>.txt and <ICAO>_Scenery_Pack.zip (one top folder)."""
    pack = zip_bytes([
        (f"{icao}_Scenery_Pack/Earth nav data/apt.dat", apt_dat_text.encode("utf-8")),
        (f"{icao}_Scenery_Pack/README.txt", b"Made-up scenery from the Scenery Editor X Gateway test server.\n"),
    ])
    return zip_bytes([
        (f"{icao}.dat", apt_dat_text.encode("utf-8")),
        (f"{icao}.txt", b"I\n800\nOBJ_DEF placeholder\n"),
        (f"{icao}_Scenery_Pack.zip", pack),
    ])


