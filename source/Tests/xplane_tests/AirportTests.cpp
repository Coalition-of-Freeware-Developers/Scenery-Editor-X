	CHECK(SignedArea(points) > 0.0);	// SW -> SE -> NE -> NW is counter-clockwise from above

	// A quarter circle: start node with an outgoing control, end node with (mirrored) control
	AptNodeChain arc;
	arc.closed = false;
	AptNode start;
	start.latitude = 47.0;
	start.longitude = -122.0;
	start.hasControl = true;
	start.controlLatitude = 47.0;
	start.controlLongitude = -121.998;		// Pulls east
	AptNode end;
	end.latitude = 47.002;
	end.longitude = -121.996;
	end.hasControl = true;
	end.controlLatitude = 47.003;			// Outgoing control points north: the incoming one points south
	end.controlLongitude = -121.996;
	arc.nodes = { start, end };
	FlattenChain(arc, projection, points);
	REQUIRE(points.size() >= 5);
	CHECK(points.front().x == Approx(0.0).margin(1e-6));
	const Point2 last = projection.ToLocal(47.002, -121.996);
