	/* @brief The binary encoding: a canonical form of every field, so equal bytes mean equal projects. */
	template<typename T>
	std::string Canonical(const T &value)
	{
		std::string bytes;
		BinaryWriter writer(bytes);
		writer.Write(value);
		return bytes;
	}

	void ClearIds(std::vector<SceneryItem> &items)
	{
		for (SceneryItem &item : items)
		{
			item.id.clear();
			ClearIds(item.children);
		}
	}

	/* @brief A folder under the temp directory, removed afterwards. */
	struct TempFolder
	{
		fs::path path;

		TempFolder()
		{
			path = fs::temp_directory_path() / ("sedx_project_tests_" + MakeItemId());
			fs::create_directories(path);
		}

		~TempFolder()
		{
			std::error_code ec;
			fs::remove_all(path, ec);
		}
	};

	fs::path FindRepoFile(const char *relative)
	{
		std::error_code ec;
		fs::path base = fs::absolute(fs::path(__FILE__), ec).parent_path();
		for (int up = 0; up < 6; ++up, base = base.parent_path())
		{
			if (fs::exists(base / relative, ec))
				return base / relative;
		}
		if (fs::exists(fs::current_path() / relative, ec))
			return fs::current_path() / relative;
		return {};
	}

	size_t CountTempFiles(const fs::path &folder)
	{
		size_t count = 0;
		for (const fs::directory_entry &entry : fs::recursive_directory_iterator(folder))
			count += entry.path().filename().string().find(".tmp-") != std::string::npos;
		return count;
	}
