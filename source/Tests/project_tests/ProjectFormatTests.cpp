		CHECK_FALSE(document.IsDirty());
		CHECK(cache.ListBackups(file).size() == 1);
		std::string backup;
		REQUIRE(ReadFileBytes(cache.ListBackups(file).front(), backup));
		CHECK(backup == saved);

