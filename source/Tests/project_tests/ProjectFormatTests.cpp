	{
		const std::string modified = document.GetProject().info.modified;
		REQUIRE(document.Save(&error));
		std::string again;
		REQUIRE(ReadFileBytes(file, again));
		CHECK(again == saved);
		CHECK(document.GetProject().info.modified == modified);
	}

