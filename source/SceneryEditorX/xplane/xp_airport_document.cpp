	bool IsAirportPackage(const fs::path &folder)
	{
		return IsFile(GetPackageAptDat(folder));
	}

	fs::path GetPackageAptDat(const fs::path &folder)
	{
		return folder / "Earth nav data" / "apt.dat";
	}

	bool IsProtectedPackage(const fs::path &folder, const fs::path &xplaneRoot)
	{
		if (xplaneRoot.empty())
			return false;
		const std::string key = PathKey(folder);
		return key.starts_with(PathKey(xplaneRoot / "Global Scenery")) || key.starts_with(PathKey(xplaneRoot / "Resources"));
	}

	bool RegisterSceneryPack(const fs::path &xplaneRoot, const fs::path &packageFolder, std::string *error)
	{
		const fs::path iniPath = xplaneRoot / "Custom Scenery" / "scenery_packs.ini";
		std::string text;
		if (!ReadTextFile(iniPath, text))
			return Fail(error, "Could not read " + iniPath.string());

		std::vector<SceneryPackEntry> entries;
		if (!ParseSceneryPacks(text, xplaneRoot, entries, error))
			return false;

		const std::string key = PathKey(packageFolder);
		for (const SceneryPackEntry &entry : entries)
		{
			if (PathKey(entry.path) == key)
				return true;	// Already listed
		}

		// X-Plane writes paths relative to its folder when the pack sits under it.
		std::string line = "SCENERY_PACK ";
		const fs::path relative = packageFolder.lexically_relative(xplaneRoot);
		if (!relative.empty() && !relative.generic_string().starts_with(".."))
			line += relative.generic_string() + "/";
		else
			line += packageFolder.generic_string() + "/";

		// Insert after the SCENERY line (the first pack listed has the highest priority).
		const size_t sceneryRow = text.find("SCENERY");
		size_t insertAt = std::string::npos;
		if (sceneryRow != std::string::npos)
		{
			insertAt = text.find('\n', sceneryRow);
			if (insertAt != std::string::npos)
			{
				++insertAt;
				// Skip the blank line WED and X-Plane leave after it.
				while (insertAt < text.size() && (text[insertAt] == '\r' || text[insertAt] == '\n'))
					++insertAt;
			}
		}
		if (insertAt == std::string::npos)
			insertAt = text.size();

		const char *newline = text.find("\r\n") != std::string::npos ? "\r\n" : "\n";
		text.insert(insertAt, line + newline);

		// Atomic: X-Plane refuses to start on a truncated scenery_packs.ini
		return VFS::WriteFileAtomic(VFS::ResolveCase(iniPath), text, error);
	}

	AptAirport MakeNewAirport(std::string id, std::string name, const double latitude, const double longitude, const AirportType type, const int elevationFt)
	{
		AptAirport airport;
		airport.type = type;
		airport.elevationFt = elevationFt;
		airport.id = std::move(id);
		airport.name = std::move(name);

		char buffer[32];
		snprintf(buffer, sizeof(buffer), "%.7f", latitude);
		airport.SetMetadata("datum_lat", buffer);
		snprintf(buffer, sizeof(buffer), "%.7f", longitude);
		airport.SetMetadata("datum_lon", buffer);
		airport.SetMetadata("gui_label", "2D");
		if (airport.id.size() == 4 && std::ranges::all_of(airport.id, [](const char c) { return c >= 'A' && c <= 'Z'; }))
			airport.SetMetadata("icao_code", airport.id);

		switch (type)
		{
			case AirportType::Land:
			{
				// A 1000 m north-south runway through the datum.
				AptRunway runway;
				runway.width = 30.0f;
				runway.surface = SurfaceAsphalt;
				runway.ends[0].designator = "18";
				runway.ends[1].designator = "36";
				MovePoint(latitude, longitude, 0.0, 500.0, runway.ends[0].latitude, runway.ends[0].longitude);
				MovePoint(latitude, longitude, 180.0, 500.0, runway.ends[1].latitude, runway.ends[1].longitude);
				airport.runways.push_back(runway);
				break;
			}
			case AirportType::Seaplane:
			{
				AptWaterRunway runway;
				runway.width = 60.0f;
				runway.ends[0].designator = "18W";
				runway.ends[1].designator = "36W";
				MovePoint(latitude, longitude, 0.0, 800.0, runway.ends[0].latitude, runway.ends[0].longitude);
				MovePoint(latitude, longitude, 180.0, 800.0, runway.ends[1].latitude, runway.ends[1].longitude);
				airport.waterRunways.push_back(runway);
				break;
			}
			case AirportType::Heliport:
			{
				AptHelipad helipad;
				helipad.designator = "H1";
				helipad.latitude = latitude;
				helipad.longitude = longitude;
				airport.helipads.push_back(helipad);
				break;
			}
		}

		AptWindsock windsock;
		MovePoint(latitude, longitude, 90.0, type == AirportType::Heliport ? 30.0 : 60.0, windsock.latitude, windsock.longitude);
		windsock.lit = true;
		windsock.name = "Windsock";
		airport.windsocks.push_back(windsock);

		AptBeacon beacon;
		MovePoint(latitude, longitude, 270.0, type == AirportType::Heliport ? 30.0 : 80.0, beacon.latitude, beacon.longitude);
		beacon.type = type == AirportType::Land ? 1 : (type == AirportType::Seaplane ? 2 : 3);
		beacon.name = "Beacon";
		airport.beacon = beacon;
		return airport;
	}
