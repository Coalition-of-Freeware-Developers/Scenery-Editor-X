	void AirportDocument::MarkDirty(const bool geometryChanged)
	{
		m_Dirty = true;
		++m_Revision;
		if (geometryChanged)
			++m_GeometryRevision;
	}

	std::string AirportDocument::GetTitle() const
	{
		std::string title = airport.id.empty() ? std::string("New airport") : airport.id;
		if (!airport.name.empty())
			title += "  " + airport.name;
		if (m_Dirty)
			title += " *";
		return title;
	}

	bool AirportDocument::Open(const AirportIndex &index, const AirportEntry &entry, AirportDocument &out, std::string *error)
	{
		AptAirport airport;
		if (!index.LoadAirport(entry, airport, error))
			return false;

		const AirportSource &source = index.GetSources()[entry.source];
		out = AirportDocument();
		out.airport = std::move(airport);
		out.m_AptDat = source.aptDat;
		out.m_Package = source.package;
		out.m_PackageName = source.packageName;
		out.m_OriginalId = entry.id;
		out.m_ReadOnly = source.source == PackageSource::GlobalScenery || source.source == PackageSource::DefaultScenery;
		out.m_Revision = 1;
		return true;
	}

	bool AirportDocument::OpenFile(const fs::path &aptDat, const std::string_view airportId, AirportDocument &out, std::string *error, const bool readOnly)
	{
		AptFile file;
		if (!LoadAptDat(aptDat, file, error))
			return false;
		if (file.airports.empty())
			return Fail(error, aptDat.string() + " holds no airports");

		const AptAirport *found = nullptr;
		if (airportId.empty())
			found = &file.airports.front();
		else
		{
			for (const AptAirport &candidate : file.airports)
			{
				if (candidate.id == airportId)
				{
					found = &candidate;
					break;
				}
			}
			if (!found)
				return Fail(error, "No airport '" + std::string(airportId) + "' in " + aptDat.string());
		}

		out = AirportDocument();
		out.airport = *found;
		out.m_AptDat = aptDat;
		out.m_Package = PackageOf(aptDat);
		out.m_PackageName = out.m_Package.filename().string();
		out.m_OriginalId = found->id;
		out.m_ReadOnly = readOnly;
		out.m_Revision = 1;
		return true;
	}

	bool AirportDocument::Create(const fs::path &packageFolder, const AptAirport &airport, AirportDocument &out, std::string *error)
	{
		if (airport.id.empty())
			return Fail(error, "The airport needs an id");
		const fs::path aptDat = GetPackageAptDat(packageFolder);
		if (IsFile(aptDat))
			return Fail(error, packageFolder.string() + " already holds an apt.dat (open it instead)");

		if (!WriteAirportInto(aptDat, airport, std::string(), error))
			return false;

		out = AirportDocument();
		out.airport = airport;
		out.m_AptDat = aptDat;
		out.m_Package = packageFolder;
		out.m_PackageName = packageFolder.filename().string();
		out.m_OriginalId = airport.id;
		out.m_ReadOnly = false;
		out.m_Revision = 1;
		return true;
	}

	bool AirportDocument::Save(std::string *error)
	{
		if (m_AptDat.empty())
			return Fail(error, "The airport has no file yet: use Save As");
		if (m_ReadOnly)
			return Fail(error, m_PackageName + " belongs to X-Plane: save the airport into a scenery pack of your own");
		if (airport.id.empty())
			return Fail(error, "The airport needs an id");

		if (!WriteAirportInto(m_AptDat, airport, m_OriginalId, error))
			return false;
		m_OriginalId = airport.id;
		m_Dirty = false;
		return true;
	}

	bool AirportDocument::SaveAs(const fs::path &packageFolder, std::string *error)
	{
		if (airport.id.empty())
			return Fail(error, "The airport needs an id");
		const fs::path aptDat = GetPackageAptDat(packageFolder);

		// Saving into the same file is a plain save; anywhere else the airport is added by id.
		const bool sameFile = !m_AptDat.empty() && PathKey(aptDat) == PathKey(m_AptDat);
		if (!WriteAirportInto(aptDat, airport, sameFile ? m_OriginalId : std::string(), error))
			return false;

		m_AptDat = aptDat;
		m_Package = packageFolder;
		m_PackageName = packageFolder.filename().string();
		m_OriginalId = airport.id;
		m_ReadOnly = false;
		m_Dirty = false;
		return true;
	}

	void AirportDocument::Detach()
	{
		m_AptDat.clear();
		m_Package.clear();
		m_PackageName.clear();
		m_OriginalId.clear();
		m_ReadOnly = false;
		m_Dirty = true;
		++m_Revision;
		++m_GeometryRevision;
	}

